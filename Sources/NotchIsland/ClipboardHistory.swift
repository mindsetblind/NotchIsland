/// Watches the general pasteboard and keeps a local history of copied text and links.
///
/// - Off until the user turns it on; nothing is read while it's off or paused.
/// - Only `changeCount` is checked (once a second, a cheap call); the contents are read once per change.
/// - Skipped: items marked concealed/transient by password managers (nspasteboard.org convention),
///   anything copied while a password manager is frontmost, files, images, and text that looks like
///   a password or token (heuristic, can be switched off).
/// - Stored only on this Mac in `~/Library/Application Support/NotchIsland/clipboard-history.json`
///   (owner-only permissions), or in memory only if the user prefers. Nothing is sent anywhere.
@MainActor
final class ClipboardHistory: ObservableObject {
    let store: ClipboardStore
    /// Copies skipped as probable secrets since launch (shown in Settings, for transparency).
    @Published private(set) var skippedSecrets = 0
    /// Called after an item is copied back from the history (the island shows a short confirmation).
    var onCopiedBack: ((ClipItem) -> Void)?

    private let settings: AppSettings
    private var timer: Timer?
    private var pruneTimer: Timer?
    private var lastChange = NSPasteboard.general.changeCount
    /// changeCount right after our own write, so copying back from the history isn't recorded again.
    private var ownChange: Int?
    private var observer: AnyCancellable?

    static var fileURL: URL { AppSettings.supportDir.appendingPathComponent("clipboard-history.json") }

    private static let skippedTypes: [NSPasteboard.PasteboardType] = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("com.agilebits.onepassword"),
    ]

    /// Password managers: whatever they put on the pasteboard is never recorded.
    private static let passwordManagers: Set<String> = [
        "com.1password.1password", "com.agilebits.onepassword7", "com.agilebits.onepassword-osx",
        "com.bitwarden.desktop", "org.keepassxc.keepassxc", "com.apple.keychainaccess", "com.apple.Passwords",
        "com.lastpass.LastPass", "com.dashlane.dashlanephonefinal", "in.sinew.Enpass-Desktop", "com.nordpass.macos.NordPass",
    ]

    init(settings: AppSettings = .shared) {
        self.settings = settings
        store = ClipboardStore(fileURL: settings.clipboardPersist ? Self.fileURL : nil, policy: Self.policy(settings))
        observer = settings.objectWillChange.sink { [weak self] in
            DispatchQueue.main.async { MainActor.assumeIsolated { self?.apply() } }
        }
        apply()
    }

    var isCollecting: Bool { settings.clipboardEnabled && !settings.clipboardPaused }

    private static func policy(_ s: AppSettings) -> ClipboardPolicy {
        ClipboardPolicy(maxItems: max(5, s.clipboardMaxItems),
                        maxAge: s.clipboardMaxAgeDays > 0 ? TimeInterval(s.clipboardMaxAgeDays) * 86_400 : nil,
                        skipLikelySecrets: s.clipboardSkipSecrets)
    }

    private func apply() {
        let policy = Self.policy(settings)
        if store.policy != policy { store.policy = policy }
        let file = settings.clipboardPersist ? Self.fileURL : nil
        if store.fileURL != file { store.fileURL = file }

        if isCollecting, timer == nil {
            // Whatever was on the clipboard before collecting started isn't recorded.
            lastChange = NSPasteboard.general.changeCount
            let t = Timer.scheduledTimer(withTimeInterval: 1, repeats: true) { [weak self] _ in
                MainActor.assumeIsolated { self?.poll() }
            }
            t.tolerance = 0.5
            timer = t
            let p = Timer.scheduledTimer(withTimeInterval: 3600, repeats: true) { [weak self] _ in
                MainActor.assumeIsolated { self?.store.prune() }
            }
            p.tolerance = 300
            pruneTimer = p
        } else if !isCollecting, timer != nil {
            timer?.invalidate()
            timer = nil
            pruneTimer?.invalidate()
            pruneTimer = nil
        }
    }

    private func poll() {
        let pb = NSPasteboard.general
        let count = pb.changeCount
        guard count != lastChange else { return }
        lastChange = count
        guard count != ownChange else { return }

        let types = pb.types ?? []
        if types.contains(where: Self.skippedTypes.contains) { return }
        let front = NSWorkspace.shared.frontmostApplication
        if let id = front?.bundleIdentifier, Self.passwordManagers.contains(id) { return }
        // Files copied in Finder also carry their name as text — that's not what people want here.
        if types.contains(.fileURL) { return }
        guard let text = pb.string(forType: .string) ?? pb.string(forType: .URL) else { return }

        if store.add(text, sourceApp: front?.localizedName) == .skippedSecret { skippedSecrets += 1 }
    }

    // MARK: Actions

    func copyBack(_ item: ClipItem) {
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.setString(item.text, forType: .string)
        ownChange = pb.changeCount
        lastChange = pb.changeCount
        store.touch(item.id)
        onCopiedBack?(item)
    }

    func confirmClearAll() {
        let alert = NSAlert()
        alert.messageText = "Удалить всю историю буфера?"
        alert.informativeText = "Будут удалены все записи, включая закреплённые. Файл истории удаляется сразу. Это нельзя отменить."
        alert.addButton(withTitle: "Удалить")
        alert.addButton(withTitle: "Отмена")
        alert.buttons.first?.hasDestructiveAction = true
        NSApp.activate(ignoringOtherApps: true)
        guard alert.runModal() == .alertFirstButtonReturn else { return }
        store.clearAll()
    }
}

// MARK: - Island tab

struct ClipboardTab: View {
    @ObservedObject var model: IslandModel
    @ObservedObject var history: ClipboardHistory
    @ObservedObject var store: ClipboardStore
    @ObservedObject private var settings = AppSettings.shared

    var body: some View {
        if !settings.clipboardEnabled {
            HStack(spacing: 14) {
                tile("doc.on.clipboard")
                VStack(alignment: .leading, spacing: 8) {
                    Text("История буфера обмена").font(.system(size: 13, weight: .semibold))
                    Text("Текст и ссылки хранятся только на этом Mac. Скрытое менеджерами паролей и похожее на токены не записывается.")
                        .font(.system(size: 11)).foregroundStyle(.secondary)
                        .fixedSize(horizontal: false, vertical: true)
                    PillButton(title: "Включить") { settings.clipboardEnabled = true }
                }
                Spacer(minLength: 0)
            }
        } else {
            HStack(spacing: 10) {
                VStack(spacing: 4) {
                    IconButton(systemName: "magnifyingglass", size: 12) { model.openClipboardSearch() }
                        .help("Поиск в истории")
                        .accessibilityLabel("Поиск в истории буфера")
                    IconButton(systemName: settings.clipboardPaused ? "play.fill" : "pause.fill", size: 11) {
                        settings.clipboardPaused.toggle()
                    }
                    .foregroundStyle(settings.clipboardPaused ? Color.orange : Color.secondary)
                    .help(settings.clipboardPaused ? "Продолжить запись" : "Приостановить запись")
                    .accessibilityLabel(settings.clipboardPaused ? "Продолжить запись буфера" : "Приостановить запись буфера")
                    Spacer(minLength: 0)
                }
                .frame(width: 30)

                if store.items.isEmpty {
                    VStack(alignment: .leading, spacing: 4) {
                        Text(settings.clipboardPaused ? "Запись приостановлена" : "Пока пусто")
                            .font(.system(size: 13, weight: .semibold))
                        Text("Скопируй текст или ссылку — они появятся здесь. Клик по карточке копирует снова.")
                            .font(.system(size: 11)).foregroundStyle(.secondary)
                            .fixedSize(horizontal: false, vertical: true)
                    }
                    Spacer(minLength: 0)
                } else {
                    HScroll {
                        HStack(spacing: 8) {
                            ForEach(store.items) { item in
                                ClipCard(history: history, item: item)
                                    .transition(.scale(0.8).combined(with: .opacity))
                            }
                        }
                        .padding(.horizontal, 2)
                    }
                }
            }
        }
    }

    private func tile(_ symbol: String) -> some View {
        RoundedRectangle(cornerRadius: 14, style: .continuous).fill(.white.opacity(0.08))
            .frame(width: IslandModel.artworkSize, height: IslandModel.artworkSize)
            .overlay(Image(systemName: symbol).font(.system(size: 28)).foregroundStyle(.secondary))
    }
}

/// One history entry: click copies it back; hover shows pin / delete.
struct ClipCard: View {
    @ObservedObject var history: ClipboardHistory
    let item: ClipItem
    var width: CGFloat = 148
    @State private var hover = false
    @State private var copied = false

    var body: some View {
        VStack(alignment: .leading, spacing: 4) {
            HStack(spacing: 4) {
                Image(systemName: item.kind == .link ? "link" : "text.alignleft")
                if item.pinned { Image(systemName: "pin.fill").foregroundStyle(.orange) }
                Text(item.sourceApp ?? "").lineLimit(1)
                Spacer(minLength: 0)
            }
            .font(.system(size: 9.5, weight: .medium))
            .foregroundStyle(.secondary)
            Text(item.text.trimmingCharacters(in: .whitespacesAndNewlines))
                .font(.system(size: 11))
                .foregroundStyle(item.kind == .link ? Color(red: 0.55, green: 0.78, blue: 1) : .white)
                .lineLimit(3)
                .truncationMode(.tail)
                .frame(maxWidth: .infinity, maxHeight: .infinity, alignment: .topLeading)
            Text(item.copiedAt, style: .relative)
                .font(.system(size: 9).monospacedDigit())
                .foregroundStyle(.tertiary)
                .lineLimit(1)
        }
        .padding(8)
        .frame(width: width, height: IslandModel.artworkSize)
        .background(RoundedRectangle(cornerRadius: 12, style: .continuous).fill(.white.opacity(hover ? 0.13 : 0.07)))
        .overlay {
            if copied {
                RoundedRectangle(cornerRadius: 12, style: .continuous).fill(.black.opacity(0.6))
                    .overlay(Label("Скопировано", systemImage: "checkmark").font(.system(size: 11, weight: .semibold)))
                    .transition(.opacity)
            }
        }
        .overlay(alignment: .topTrailing) {
            if hover && !copied {
                HStack(spacing: 0) {
                    small(item.pinned ? "pin.slash" : "pin", help: item.pinned ? "Открепить" : "Закрепить") {
                        history.store.setPinned(item.id, !item.pinned)
                    }
                    small("xmark", help: "Удалить из истории") { history.store.remove(item.id) }
                }
                .background(Capsule().fill(.black.opacity(0.7)))
                .padding(4)
                .transition(.opacity)
            }
        }
        .contentShape(Rectangle())
        .onHover { h in withAnimation(.easeOut(duration: 0.12)) { hover = h } }
        .onTapGesture { copy() }
        .contextMenu {
            Button("Скопировать") { copy() }
            if item.kind == .link, let url = URL(string: item.text) {
                Button("Открыть ссылку") { NSWorkspace.shared.open(url) }
            }
            Button(item.pinned ? "Открепить" : "Закрепить") { history.store.setPinned(item.id, !item.pinned) }
            Divider()
            Button("Удалить из истории") { history.store.remove(item.id) }
        }
        .help(String(item.text.prefix(300)))
        .accessibilityElement(children: .ignore)
        .accessibilityLabel((item.kind == .link ? "Ссылка: " : "Текст: ") + item.preview)
        .accessibilityHint("Скопировать снова")
        .accessibilityAddTraits(.isButton)
        .accessibilityAction { copy() }
    }

    private func copy() {
        history.copyBack(item)
        withAnimation(.easeOut(duration: 0.15)) { copied = true }
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.9) {
            withAnimation(.easeOut(duration: 0.2)) { copied = false }
        }
    }

    private func small(_ symbol: String, help: String, action: @escaping () -> Void) -> some View {
        Button(action: action) {
            Image(systemName: symbol).font(.system(size: 9, weight: .bold)).frame(width: 20, height: 18).contentShape(Rectangle())
        }
        .buttonStyle(.plain)
        .help(help)
        .accessibilityLabel(help)
    }
}

// MARK: - Search panel

/// Floating search window. It's a non-activating panel: it takes keyboard focus for the search field
/// without activating NotchIsland, so the app you were in stays frontmost and gets focus back on close.
final class ClipboardSearchPanel: NSPanel {
    override var canBecomeKey: Bool { true }
    override var canBecomeMain: Bool { false }

    init() {
        super.init(contentRect: NSRect(x: 0, y: 0, width: 480, height: 380),
                   styleMask: [.nonactivatingPanel, .fullSizeContentView, .borderless],
                   backing: .buffered, defer: true)
        isFloatingPanel = true
        level = .floating
        hidesOnDeactivate = false
        isOpaque = false
        backgroundColor = .clear
        hasShadow = true
        isMovableByWindowBackground = true
        collectionBehavior = [.canJoinAllSpaces, .fullScreenAuxiliary, .transient, .ignoresCycle]
        isReleasedWhenClosed = false
    }

    /// Clicking anywhere else closes it, like Spotlight.
    override func resignKey() {
        super.resignKey()
        close()
    }

    override func cancelOperation(_ sender: Any?) { close() }

    /// Buttons with their own shortcuts (e.g. the pet's ⌘Z "Отменить") go first; then the editing keys.
    override func performKeyEquivalent(with event: NSEvent) -> Bool {
        super.performKeyEquivalent(with: event) || EditShortcuts.handle(event)
    }
}

@MainActor
final class ClipboardSearchWindow {
    static let shared = ClipboardSearchWindow()
    private var panel: ClipboardSearchPanel?

    var isOpen: Bool { panel?.isVisible == true }

    func toggle(history: ClipboardHistory, below notch: CGRect?) {
        isOpen ? close() : show(history: history, below: notch)
    }

    func show(history: ClipboardHistory, below notch: CGRect?) {
        let panel = ClipboardSearchPanel()
        let view = ClipboardSearchView(history: history, store: history.store) { [weak self] in self?.close() }
        panel.contentView = NSHostingView(rootView: view)
        if let notch {
            panel.setFrameTopLeftPoint(NSPoint(x: (notch.midX - panel.frame.width / 2).rounded(), y: notch.minY - 10))
        } else {
            panel.center()
        }
        self.panel = panel
        panel.makeKeyAndOrderFront(nil)
    }

    func close() {
        panel?.orderOut(nil)
        panel = nil
    }
}

struct ClipboardSearchView: View {
    @ObservedObject var history: ClipboardHistory
    @ObservedObject var store: ClipboardStore
    let close: () -> Void
    @State private var query = ""
    @State private var selection = 0
    @FocusState private var focused: Bool

    private var results: [ClipItem] { store.search(query) }

    var body: some View {
        VStack(spacing: 0) {
            HStack(spacing: 8) {
                Image(systemName: "magnifyingglass").foregroundStyle(.secondary)
                TextField("Поиск в истории буфера", text: $query)
                    .textFieldStyle(.plain)
                    .font(.system(size: 15))
                    .focused($focused)
                    .onSubmit { copySelected() }
                    .onKeyPress(.downArrow) { move(1); return .handled }
                    .onKeyPress(.upArrow) { move(-1); return .handled }
                    .onKeyPress(.escape) { close(); return .handled }
                    .accessibilityLabel("Поиск в истории буфера")
                Text("\(results.count)").font(.system(size: 11).monospacedDigit()).foregroundStyle(.tertiary)
            }
            .padding(.horizontal, 14)
            .padding(.vertical, 12)
            Divider().overlay(Color.white.opacity(0.1))

            if results.isEmpty {
                VStack(spacing: 6) {
                    Image(systemName: "doc.on.clipboard").font(.system(size: 24)).foregroundStyle(.tertiary)
                    Text(store.items.isEmpty ? "История пуста" : "Ничего не найдено").foregroundStyle(.secondary)
                }
                .frame(maxWidth: .infinity, maxHeight: .infinity)
            } else {
                ScrollViewReader { proxy in
                    ScrollView {
                        LazyVStack(spacing: 2) {
                            ForEach(Array(results.enumerated()), id: \.element.id) { index, item in
                                row(item, selected: index == selection)
                                    .id(item.id)
                                    .onTapGesture { selection = index; copySelected() }
                            }
                        }
                        .padding(6)
                    }
                    .onChange(of: selection) { _, i in
                        guard results.indices.contains(i) else { return }
                        proxy.scrollTo(results[i].id)
                    }
                }
            }
            HStack {
                Text("↩ скопировать   ↑↓ выбрать   esc закрыть")
                Spacer()
                Text(history.isCollecting ? "Только на этом Mac" : "Запись выключена")
            }
            .font(.system(size: 10))
            .foregroundStyle(.tertiary)
            .padding(.horizontal, 14)
            .padding(.vertical, 8)
        }
        .frame(width: 480, height: 380)
        .background(RoundedRectangle(cornerRadius: 18, style: .continuous).fill(Color.black.opacity(0.92)))
        .overlay(RoundedRectangle(cornerRadius: 18, style: .continuous).strokeBorder(.white.opacity(0.1)))
        .foregroundStyle(.white)
        .environment(\.colorScheme, .dark)
        .onAppear { focused = true }
        .onChange(of: query) { _, _ in selection = 0 }
    }

    private func row(_ item: ClipItem, selected: Bool) -> some View {
        HStack(alignment: .top, spacing: 10) {
            Image(systemName: item.kind == .link ? "link" : "text.alignleft")
                .frame(width: 16)
                .foregroundStyle(.secondary)
            VStack(alignment: .leading, spacing: 2) {
                Text(item.text.trimmingCharacters(in: .whitespacesAndNewlines))
                    .font(.system(size: 12.5))
                    .lineLimit(2)
                HStack(spacing: 6) {
                    if item.pinned { Label("закреплено", systemImage: "pin.fill").foregroundStyle(.orange) }
                    if let app = item.sourceApp { Text(app) }
                    Text(item.copiedAt, style: .relative)
                }
                .font(.system(size: 10))
                .foregroundStyle(.tertiary)
            }
            Spacer(minLength: 0)
            Button { store.remove(item.id) } label: { Image(systemName: "xmark").font(.system(size: 9, weight: .bold)) }
                .buttonStyle(.plain)
                .foregroundStyle(.tertiary)
                .help("Удалить из истории")
                .accessibilityLabel("Удалить из истории")
        }
        .padding(.horizontal, 8)
        .padding(.vertical, 6)
        .background(RoundedRectangle(cornerRadius: 9, style: .continuous).fill(.white.opacity(selected ? 0.14 : 0)))
        .contentShape(Rectangle())
        .contextMenu {
            Button(item.pinned ? "Открепить" : "Закрепить") { store.setPinned(item.id, !item.pinned) }
            Button("Удалить из истории") { store.remove(item.id) }
        }
    }

    private func move(_ delta: Int) {
        guard !results.isEmpty else { return }
        selection = min(max(selection + delta, 0), results.count - 1)
    }

    private func copySelected() {
        let r = results
        guard r.indices.contains(selection) else { return }
        history.copyBack(r[selection])
        close()
    }
}
